"""코드 색인용 추출과 이름 찾기 (6단계 코드 검색). 원본 Sources/DigUpKit/CodeExtractor.swift(CodeExtractor, CodeLookup)를
옮겼다. 소스 파일·저장소 문서·노트북을 "줄 묶음"(노트북은 셀 묶음)으로 자르고, 묶음마다 첫·마지막 줄을 남겨 결과가 그
줄에서 열리게 한다.

원본과 다르게 한 것:
- 글자 인코딩: 원본은 UTF-8, 안 되면 ISO-8859-1. 한국어 Windows의 오래된 코드는 CP949가 많아 UTF-8 → CP949 → Latin-1
  순으로 읽는다.
- 저장소 찾기: 원본처럼 사용자 홈 폴더에서 멈춘다. 파일·폴더 이름만 확인하고 내용은 읽지 않는다.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from pathlib import Path

from . import rules
from .extractors import ExtractError, LeftOut

PREFIX = "code:"        # 원본 CodeQuery.prefix: 이 접두사로 시작하는 검색만 코드 색인을 본다


def query_text(text: str) -> str | None:
    """"code: retry with backoff" → "retry with backoff". "code:"만 쓰면 "", 코드 검색이 아니면 None. 대소문자 무시."""
    trimmed = text.lstrip()
    if trimmed[:len(PREFIX)].lower() != PREFIX:
        return None
    return trimmed[len(PREFIX):].strip()


STRETCH = 1800          # 원본 IndexOptions.codeStretch: 실제 코드 평가에서 1,200·3,600보다 나았다
LONGEST_PIECE = 4000    # 모델 입력 한도(2,048 토큰) 안에 들도록 한 묶음의 상한
GENERATED_MARKS = ("DO NOT EDIT", "@generated", "Code generated by", "Autogenerated by", "Generated by the protocol")
_CLOSERS = {"end", "fi", "done", "esac", "@end", "#endif", "end;", "end)"}


@dataclass(frozen=True)
class Piece:
    text: str
    first: int     # 첫 줄(노트북은 첫 셀), 1부터
    last: int


@dataclass
class CodeFile:
    pieces: list[Piece]
    title: str            # 모델에게 줄 제목: 저장소 이름부터의 경로 ("billing/payments/retry.py")
    repo: str | None
    lines: int
    cells: int | None     # 노트북의 셀 수, 그 밖에는 None


def read(path: str) -> CodeFile:
    """파일 하나. 바이너리·비밀 키·생성된 코드·압축된 코드는 LeftOut(건너뜀)으로 알린다."""
    with open(path, "rb") as f:
        data = f.read(rules.MAX_NOTEBOOK_BYTES + 1)
    repo, title = place(path)
    if rules.extension(os.path.basename(path)) == "ipynb":
        cells = notebook_cells(data)
        text = "\n".join(cells)
        if len(text.encode("utf-8")) > rules.MAX_CODE_BYTES:
            raise LeftOut(f"cells over {rules.MAX_CODE_BYTES >> 20} MB")
        check(text, source=True)
        return CodeFile(cell_pieces(cells), title, repo, line_count(text), len(cells))
    if b"\0" in data[:8000]:
        raise LeftOut("not text")
    text = decode(data)
    check(text, source=rules.extension(os.path.basename(path)) in rules.CODE_SOURCE_EXTENSIONS)
    return CodeFile(lines(text), title, repo, line_count(text), None)


def decode(data: bytes) -> str:
    for encoding in ("utf-8-sig", "cp949"):
        try:
            return data.decode(encoding)
        except UnicodeDecodeError:
            continue
    return data.decode("latin-1")


def check(text: str, source: bool) -> None:
    """읽을 필요가 없는 코드: 개인 키가 들었거나, (소스 파일이면) 프로그램이 만들었거나 압축(minify)된 것."""
    if "PRIVATE KEY-----" in text:
        raise LeftOut("holds a private key")
    if not source:
        return
    top = text[:1000]
    for mark in GENERATED_MARKS:
        if mark in top:
            raise LeftOut(f"made by a program ({mark})")
    count = max(1, line_count(text))
    if len(text) // count > 300 and any(len(line) > 3000 for line in text.split("\n")):
        raise LeftOut(f"minified ({len(text) // count} characters a line)")


def line_count(text: str) -> int:
    count = text.count("\n")
    return count if text.endswith("\n") or not text else count + 1


def _split_lines(text: str) -> list[str]:
    parts = re.split(r"\r\n|\n|\r", text)
    if parts and parts[-1] == "":
        parts.pop()
    return parts


def lines(text: str, size: int = STRETCH) -> list[Piece]:
    """원본 CodeExtractor.lines: 줄을 자르지 않고 size자까지 묶는다. 가능하면 코드가 끊기는 곳(왼쪽 끝에서 시작하는 새
    블록 앞, 빈 줄 뒤)에서, 묶음의 뒤쪽 60% 안에서 끊는다. 블록 중간에서 끊어야 했으면 마지막 두 줄을 다음 묶음에
    겹쳐 넣어, 경계에 걸친 코드도 한 번은 통째로 읽힌다."""
    rows = _split_lines(text)
    count = len(rows)
    offsets = [0]
    for row in rows:
        offsets.append(offsets[-1] + len(row) + 1)

    def blank(i: int) -> bool:
        return not rows[i].strip()

    def starts_block(i: int) -> bool:
        row = rows[i]
        if not row or row[0].isspace():
            return False
        return row[0] not in "})]" and row.strip() not in _CLOSERS

    pieces: list[Piece] = []
    start = 0
    while start < count:
        while start < count and blank(start):
            start += 1
        if start >= count:
            break
        end = start + 1
        while end < count and offsets[end + 1] - offsets[start] <= size:
            end += 1
        natural = end >= count
        if not natural:
            floor = offsets[start] + size * 2 // 5

            def last_break(is_break) -> int | None:
                line = end
                while line > start + 1 and offsets[line] >= floor:
                    if is_break(line):
                        return line
                    line -= 1
                return None

            cut = last_break(lambda i: starts_block(i) and blank(i - 1))
            if cut is None:
                cut = last_break(lambda i: blank(i - 1) or starts_block(i))
            if cut is not None:
                end, natural = cut, True
        last = end
        while last > start + 1 and blank(last - 1):
            last -= 1
        body = "\n".join(rows[start:last])[:LONGEST_PIECE]
        pieces.append(Piece(body, start + 1, last))
        start = end if natural else max(end - 2, start + 1)
    return pieces


def notebook_cells(data: bytes) -> list[str]:
    """Jupyter 노트북의 셀(코드와 메모) 본문. 출력(그림·표·로그)은 읽지 않는다."""
    try:
        notebook = json.loads(decode(data))
    except ValueError as error:
        raise ExtractError("not a notebook") from error
    if not isinstance(notebook, dict):
        raise ExtractError("not a notebook")
    cells = notebook.get("cells")
    if cells is None:
        sheets = notebook.get("worksheets") or [{}]
        cells = sheets[0].get("cells", []) if isinstance(sheets[0], dict) else []
    out = []
    for cell in cells if isinstance(cells, list) else []:
        source = cell.get("source", cell.get("input", "")) if isinstance(cell, dict) else ""
        out.append("".join(source) if isinstance(source, list) else str(source or ""))
    return out


def cell_pieces(cells: list[str], size: int = STRETCH) -> list[Piece]:
    """셀을 통째로 size자까지 묶는다. 더 긴 셀은 줄 묶음으로 나누고 모두 그 셀을 가리킨다."""
    pieces: list[Piece] = []
    text, first, last = "", 0, 0
    for index, cell in enumerate(cells, 1):
        body = cell.strip()
        if not body:
            continue
        if len(body) > size:
            if text:
                pieces.append(Piece(text, first, last))
                text = ""
            pieces += [Piece(p.text, index, index) for p in lines(body, size)]
            continue
        if text and len(text) + 2 + len(body) > size:
            pieces.append(Piece(text, first, last))
            text = ""
        if not text:
            first, text = index, body
        else:
            text += "\n\n" + body
        last = index
    if text:
        pieces.append(Piece(text, first, last))
    return pieces


def place(path: str) -> tuple[str | None, str]:
    """파일이 든 저장소(.git이나 프로젝트 표지가 있는 폴더)와 제목: 저장소 이름부터의 경로. 없으면 폴더 이름/파일 이름.
    원본 실험: 파일 이름만 쓸 때보다 상위 5위 22 → 24/27, MRR 0.69 → 0.79."""
    p = Path(path)
    home = Path.home()
    for folder in p.parents:
        if folder.parent == folder or folder == home:
            break
        if (folder / ".git").exists() or rules.is_project_root(folder):
            return str(folder), p.relative_to(folder.parent).as_posix()
    return None, "/".join(p.parts[-2:])


