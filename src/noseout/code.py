def language(path: str) -> str:
    name = os.path.basename(path)
    ext = rules.extension(name)
    if ext in LANGUAGES:
        return LANGUAGES[ext]
    if name in rules.CODE_FILE_NAMES or name.startswith("Dockerfile"):
        return name
    return ext.upper() or "텍스트"


# 이름 찾기 (원본 CodeLookup)

_DEFINERS = {
    "def", "func", "fn", "fun", "function", "class", "struct", "enum", "protocol", "interface", "trait", "type",
    "typealias", "actor", "extension", "impl", "module", "namespace", "object", "record", "macro", "const", "let",
    "var", "val", "union", "mod", "sub", "@interface", "@implementation", "@protocol", "#define", "function*",
}
_USERS = {
    "return", "await", "yield", "throw", "new", "else", "case", "print", "echo", "assert", "not", "and", "or", "in",
    "is", "do", "go", "defer", "try", "catch", "if", "while", "for", "typeof", "delete", "raise", "import", "from",
}
_COMMENT_STARTS = ("//", "#", "/*", "*", "--", '"""', "'''", "<!--", ";")
_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*(?:(?:\.|::|->|#)[A-Za-z_$][A-Za-z0-9_$]*)*$")


def identifier(query: str) -> list[str] | None:
    """검색어가 코드의 이름 하나면(snake_case, camelCase, 점·숫자 포함) FTS가 저장한 단어들로. 보통 단어("retry")는 None."""
    name = query.strip()
    if name.endswith("()"):
        name = name[:-2]
    if not _IDENTIFIER.match(name):
        return None
    camel = any(c.isupper() for c in name[1:]) and any(c.islower() for c in name)
    if not (camel or any(c in "_.:#$" or c.isdigit() for c in name)):
        return None
    return [w for w in re.split(r"[^0-9a-z]+", name.lower()) if w]


def phrase(words: list[str]) -> str:
    return '"' + " ".join(words) + '"'


def defines_something(word: str) -> bool:
    return word in _DEFINERS and word not in ("let", "var", "const", "val")


def _is_name_char(ch: str) -> bool:
    return ch.isalnum() or ch in "_$"


def _occurrences(name: str, line: str) -> list[tuple[int, int]]:
    found, lower, target, start = [], line.lower(), name.lower(), 0
    while (at := lower.find(target, start)) >= 0:
        end = at + len(target)
        if (at == 0 or not _is_name_char(line[at - 1])) and (end == len(line) or not _is_name_char(line[end])):
            found.append((at, end))
        start = end
    return found


def _strength(before: str, after: str, line: str) -> int:
    previous = before.split()[-1] if before.split() else ""
    if previous in _DEFINERS:
        return 2
    if before.startswith("func (") and before.endswith(")"):
        return 2
    if before.startswith(("- (", "+ (")):
        return 2 if after.startswith((":", "{", ";")) or not after else 0
    if not after.startswith("(") or not before or previous in _USERS or any(c in "=(,.!?" for c in before) \
            or "->" in before or not (before[-1].isalnum() or before[-1] in "*&>_]"):
        return 0
    return 1 if line.strip().endswith(";") else 2


def definition(name: str, text: str, first: int) -> tuple[int, int] | None:
    """text(첫 줄이 first인 묶음)에서 name을 정의하는 줄과 확실한 정도(2: 정의, 1: 선언). 쓰기만 하면 None."""
    best = None
    for offset, line in enumerate(_split_lines(text)):
        for start, end in _occurrences(name, line):
            strength = _strength(line[:start].strip(), line[end:].strip(), line)
            if strength > (best[1] if best else 0):
                best = (first + offset, strength)
            if strength == 2:
                return best
    return best


def _has(word: str, line: str) -> bool:
    lower, start = line.lower(), 0
    while (at := lower.find(word, start)) >= 0:
        if at == 0 or not lower[at - 1].isalnum() or line[at].isupper():
            return True
        start = at + len(word)
    return False


def first_line(words: list[str], text: str, first: int) -> int | None:
    """열 줄: 검색어 단어가 든 줄 가운데 무언가를 정의하는 첫 줄, 없으면 주석이 아닌 첫 줄, 없으면 첫 줄."""
    words = [w.lower() for w in words if len(w) >= 2]
    if not words:
        return None
    first_code = first_any = None
    for offset, line in enumerate(_split_lines(text)):
        if not any(_has(w, line) for w in words):
            continue
        stripped = line.strip()
        if any(defines_something(w) for w in stripped.split()[:4]):
            return first + offset
        if first_code is None and not stripped.startswith(_COMMENT_STARTS):
            first_code = offset
        if first_any is None:
            first_any = offset
    chosen = first_code if first_code is not None else first_any
    return None if chosen is None else first + chosen


def summary(text: str) -> str:
    """결과 목록용 한 줄: 무언가를 정의하는 첫 줄, 없으면 주석·import가 아닌 첫 줄 (원본 CodeExtractor.summary)."""
    rows = [r.strip() for r in _split_lines(text) if r.strip()]
    found = next((r for r in rows if any(defines_something(w) for w in r.split()[:4])), None)
    if found is None:
        found = next((r for r in rows if not r.startswith(
            ("//", "#", "/*", "*", "--", '"""', "import ", "from ", "#include", "using ", "package ", "}", ")", "@"))),
            rows[0] if rows else "")
    return found[:160] + "…" if len(found) > 160 else found


def context(text: str, first: int, focus: int | None, before: int = 3, after: int = 8) -> list[tuple[int, str]]:
    """결과에 보일 코드 문맥: 열 줄(focus) 앞뒤의 (줄 번호, 줄) 목록. focus가 없으면 묶음의 첫 줄부터."""
    rows = _split_lines(text)
    at = (focus - first) if focus is not None else 0
    at = min(max(at, 0), max(len(rows) - 1, 0))
    start = max(0, at - before) if focus is not None else 0
    return [(first + i, rows[i]) for i in range(start, min(len(rows), at + after + 1))]
