def test_lines_keep_line_numbers_and_cover_every_line():
    text = "\n".join(f"def f{n}():\n    return {n}\n" for n in range(600))
    pieces = code.lines(text)
    rows = text.split("\n")
    assert len(pieces) > 6 and all(len(p.text) <= code.STRETCH for p in pieces)
    for piece in pieces:
        assert piece.text.split("\n") == rows[piece.first - 1:piece.last]   # 1부터 센 줄 번호가 실제 줄과 맞다
    covered = set()
    for piece in pieces:
        covered |= set(range(piece.first, piece.last + 1))
    assert all(i + 1 in covered for i, row in enumerate(rows) if row.strip())
    assert all(p.text.startswith("def ") for p in pieces)   # 블록 경계에서 끊는다
    crlf = code.lines("a = 1\r\n\r\nb = 2\r\n")
    assert [(p.first, p.last) for p in crlf] == [(1, 3)] and crlf[0].text == "a = 1\n\nb = 2"


