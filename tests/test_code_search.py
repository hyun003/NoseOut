    got = sorted(Path(f.path).relative_to(repo).as_posix() for f in found.files)
    # 비밀·데이터·압축·라이선스·의존성·빌드·서브모듈·git 무시·1MB 초과는 빠진다. 바이너리·생성 코드는 읽을 때 건너뛴다
