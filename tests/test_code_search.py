RETRY = '''"""Network helpers."""
import random
import time


def retry_with_backoff(operation, attempts=5, base_delay=0.5):
    """Call operation until it succeeds, waiting longer after each failure (exponential backoff with jitter)."""
    for attempt in range(attempts):
        try:
            return operation()
        except ConnectionError:
            time.sleep(base_delay * 2 ** attempt + random.random())
    raise RuntimeError("gave up")


def fetch_invoice(client, number):
    return retry_with_backoff(lambda: client.get(f"/invoices/{number}"))
'''

PARSER = '''export function parseCsvLine(line: string): string[] {
  // split a comma separated line, keeping quoted commas
  const cells: string[] = [];
  let current = "";
  let quoted = false;
  for (const ch of line) {
    if (ch === '"') quoted = !quoted;
    else if (ch === "," && !quoted) { cells.push(current); current = ""; }
    else current += ch;
  }
  cells.push(current);
  return cells;
}
'''


def git(*args, cwd):
    return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True,
                          env={**os.environ, "GIT_CONFIG_NOSYSTEM": "1", "GIT_AUTHOR_NAME": "t",
                               "GIT_AUTHOR_EMAIL": "t@example.invalid", "GIT_COMMITTER_NAME": "t",
                               "GIT_COMMITTER_EMAIL": "t@example.invalid"})


def make_repo(tmp_path: Path, with_git: bool = True) -> Path:
    """합성 코드 저장소: 색인할 것과 빼야 할 것(의존성·빌드·git 무시·비밀·데이터·생성·큰 파일)을 함께 둔다."""
    repo = tmp_path / "code" / "billing"
    for folder in ("src", "web", "node_modules/lodash", "vendor/lib", "build", "dist", "notes", "submod", "cache"):
        (repo / folder).mkdir(parents=True, exist_ok=True)
    (repo / "src" / "net.py").write_text(RETRY, encoding="utf-8")
    (repo / "web" / "parser.ts").write_text(PARSER, encoding="utf-8")
    (repo / "README.md").write_text("# Billing\nInvoices and payment retries.\n", encoding="utf-8")
    (repo / "Makefile").write_text("test:\n\tpytest -q\n", encoding="utf-8")
    (repo / "node_modules" / "lodash" / "index.js").write_text("module.exports = {}\n", encoding="utf-8")
    (repo / "vendor" / "lib" / "third.py").write_text("def vendored():\n    pass\n", encoding="utf-8")
    (repo / "build" / "out.js").write_text("var built = 1;\n", encoding="utf-8")
    (repo / "dist" / "app.js").write_text("var dist = 1;\n", encoding="utf-8")
    (repo / "submod" / ".git").write_text("gitdir: ../.git/modules/submod\n", encoding="utf-8")
    (repo / "submod" / "inner.py").write_text("def submodule_code():\n    pass\n", encoding="utf-8")
    (repo / "cache" / "ignored_by_git.py").write_text("def ignored():\n    pass\n", encoding="utf-8")
    (repo / "settings.json").write_text('{"a": 1}\n', encoding="utf-8")
    (repo / "package-lock.json").write_text("{}\n", encoding="utf-8")
    (repo / "app.min.js").write_text("var a=1;\n", encoding="utf-8")
    (repo / "LICENSE.txt").write_text("MIT\n", encoding="utf-8")
    (repo / ".env").write_text("TOKEN=x\n", encoding="utf-8")
    (repo / "id_rsa.py").write_text("x = 1\n", encoding="utf-8")
    (repo / "generated_pb2.py").write_text("# Generated by the protocol buffer compiler.  DO NOT EDIT!\nx = 1\n",
                                           encoding="utf-8")
    (repo / "big.py").write_bytes(b"x = 1\n" * (rules.MAX_CODE_BYTES // 6 + 10))
    (repo / "blob.py").write_bytes(b"\x00\x01binary\x00" * 10)
    if with_git:
        (repo / ".gitignore").write_text("cache/\n", encoding="utf-8")
        if git("init", "-q", cwd=repo).returncode != 0:
            pytest.skip("git init failed")
    return repo


